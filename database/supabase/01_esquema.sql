begin;

-- Orden inverso por dependencias
drop table if exists "Conversaciones" cascade;
drop table if exists "Respuestas" cascade;
drop table if exists "Usuarios" cascade;
drop table if exists "Preguntas" cascade;

-- ---------------------------------------------------------------------------
-- Usuarios
-- ---------------------------------------------------------------------------
create table "Usuarios" (
    "Id"            integer      generated by default as identity primary key,
    "Nombre"        varchar(100) not null,
    "Email"         varchar(150) not null,
    "PasswordHash"  text         not null,        -- hash BCrypt, portable entre .NET y Postgres
    "Rol"           varchar(20)  not null default 'User',   -- 'Admin' | 'User'
    "FechaCreacion" timestamptz  not null default now()
);

create unique index "IX_Usuarios_Email" on "Usuarios" ("Email");

-- ---------------------------------------------------------------------------
-- Preguntas (FAQs)
-- ---------------------------------------------------------------------------
create table "Preguntas" (
    "Id"             integer      generated by default as identity primary key,
    "TextoPregunta"  varchar(500) not null,
    "Categoria"      varchar(100) not null,
    "EstadoActivo"   boolean      not null default true
);

-- ---------------------------------------------------------------------------
-- Respuestas (1 Pregunta -> N Respuestas)
-- ---------------------------------------------------------------------------
create table "Respuestas" (
    "Id"                  integer     generated by default as identity primary key,
    "PreguntaId"          integer     not null
        references "Preguntas" ("Id") on delete cascade,
    "TextoRespuesta"      text        not null,
    "UltimaActualizacion" timestamptz not null default now()
);

create index "IX_Respuestas_PreguntaId" on "Respuestas" ("PreguntaId");

-- ---------------------------------------------------------------------------
-- Conversaciones (historial del chat)
-- ---------------------------------------------------------------------------
create table "Conversaciones" (
    "Id"              integer  generated by default as identity primary key,
    "SessionId"       uuid     not null,
    "UsuarioId"       integer  null
        references "Usuarios" ("Id") on delete set null,
    "PreguntaUsuario" text     not null,
    "RespuestaBot"    text     not null,
    "Timestamp"       timestamptz not null default now()
);

create index "IX_Conversaciones_SessionId" on "Conversaciones" ("SessionId");
create index "IX_Conversaciones_UsuarioId" on "Conversaciones" ("UsuarioId");

commit;
